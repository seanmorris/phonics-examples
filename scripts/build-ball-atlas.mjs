// Builds games/php-billiards/art/svg/ball-atlas.svg: sixteen 256×128 equirectangular ball skins in the colours of
// pre-1970 Bakelite sets, on aged ivory, numbered in Lobster (Impallari Type, SIL OFL 1.1).
//
//   node scripts/build-ball-atlas.mjs                     rebuild the SVG from art/typography/ball-numerals.json
//   node scripts/build-ball-atlas.mjs --extract font.ttf  first refresh the digit outlines from a Lobster font file
//
// Only the digit outlines are kept in the repository, so the atlas never depends on an installed or bundled font.
import fs from 'node:fs';
import opentype from 'opentype.js';

const root = new URL('../games/php-billiards/art/', import.meta.url);
const numerals = new URL('typography/ball-numerals.json', root);
const extract = process.argv.indexOf('--extract');

if(extract >= 0)
{
	const font = opentype.loadSync(process.argv[extract + 1]);
	const digits = {};
	for(const digit of '0123456789')
	{
		const glyph = font.charToGlyph(digit);
		// Commands as [type, x1, y1, ...] in font units with y pointing down from the baseline, ready to place.
		const commands = glyph.getPath(0, 0, font.unitsPerEm).commands.map(({type, x1, y1, x2, y2, x, y}) =>
			[type, ...[x1, y1, x2, y2, x, y].filter(value => value !== undefined).map(value => Math.round(value * 10) / 10)]);
		digits[digit] = {advance: glyph.advanceWidth, commands};
	}
	fs.writeFileSync(numerals, JSON.stringify({
		source: 'Digit outlines from Lobster by Impallari Type (https://github.com/impallari/The-Lobster-Font), '
			+ 'licensed under the SIL Open Font License 1.1; see Lobster-OFL.txt.'
		, unitsPerEm: font.unitsPerEm, digits
	}, null, '\t') + '\n');
}

const {unitsPerEm, digits} = JSON.parse(fs.readFileSync(numerals, 'utf8'));
// Sampled from a photographed Bakelite set and lifted to their lit faces: warm, saturated, with solids and stripes of
// the same number in noticeably different shades.
const colors = [
	'#f1ead6','#e9a019','#1d3a9e','#c8143a','#4a2c8a','#f0461e','#12806a','#932c48'
	, '#1a1d22','#f6b21a','#1a50d8','#e81850','#5838a8','#f56a40','#0f6e55','#7a2034'
];
const ivory = '#ece2c8', face = '#efe6ce', ink = '#16120f';
const digitHeight = 26, circle = 21, tracking = -40;

const symbols = [];
const cells = [];
for(let number = 0; number < 16; number++)
{
	const x = number % 4 * 256, y = Math.floor(number / 4) * 128;
	if(number === 0) {cells.push(`<g transform="translate(${x} ${y})"><rect width="256" height="128" fill="${colors[0]}"/></g>`); continue;}

	// One path per number: its digits set side by side, then scaled to the digit height and centred in each spot.
	let pen = 0;
	const path = [];
	for(const digit of String(number))
	{
		const {advance, commands} = digits[digit];
		for(const [type, ...coordinates] of commands) path.push(type + coordinates
			.map((value, index) => (index % 2 ? value + unitsPerEm : value + pen).toFixed(1)).join(' '));
		pen += advance + tracking;
	}
	const box = pathBounds(path.join(' '));
	symbols.push(`<symbol id="n${number}" viewBox="${box.x1.toFixed(1)} ${box.y1.toFixed(1)} ${(box.x2 - box.x1).toFixed(1)} ${(box.y2 - box.y1).toFixed(1)}"><path d="${path.join(' ')}"/></symbol>`);
	const scale = digitHeight / 750;
	const width = (box.x2 - box.x1) * scale, height = (box.y2 - box.y1) * scale;
	const stripe = number > 8;
	const spots = [64,192].map(cx => `<circle cx="${cx}" cy="64" r="${circle}" fill="${face}"/>`
		+ `<use href="#n${number}" x="${(cx - width / 2).toFixed(3)}" y="${(64 - height / 2).toFixed(3)}" width="${width.toFixed(3)}" height="${height.toFixed(3)}"/>`);
	cells.push(`<g transform="translate(${x} ${y})" color="${colors[number]}">`
		+ (stripe ? `<rect width="256" height="128" fill="${ivory}"/><rect y="41" width="256" height="46" fill="currentColor"/>`
			: `<rect width="256" height="128" fill="currentColor"/>`)
		+ spots.join('') + '</g>');
}

fs.writeFileSync(new URL('svg/ball-atlas.svg', root), `<svg xmlns="http://www.w3.org/2000/svg" width="2048" height="1024" viewBox="0 0 1024 512">
  <!-- Generated by scripts/build-ball-atlas.mjs. Numerals: Lobster by Impallari Type, SIL OFL 1.1 (art/typography/Lobster-OFL.txt). -->
  <defs>
    ${symbols.join('\n    ')}
  </defs>
  <rect width="1024" height="512" fill="${ivory}"/>
  <!-- Each 256×128 viewBox cell rasterizes to a 512×256 equirectangular ball skin. Number spots appear on opposing faces. -->
  <g fill="${ink}">
    ${cells.join('\n    ')}
  </g>
</svg>
`);

/** Bounding box of an SVG path whose absolute coordinates are space-separated pairs, control points included. */
function pathBounds(data)
{
	const values = data.match(/-?\d+(?:\.\d+)?/g).map(Number);
	const box = {x1: Infinity, y1: Infinity, x2: -Infinity, y2: -Infinity};
	for(let index = 0; index + 1 < values.length; index += 2)
	{
		box.x1 = Math.min(box.x1, values[index]); box.x2 = Math.max(box.x2, values[index]);
		box.y1 = Math.min(box.y1, values[index + 1]); box.y2 = Math.max(box.y2, values[index + 1]);
	}
	return box;
}
