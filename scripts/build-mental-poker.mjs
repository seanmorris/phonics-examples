import {mkdtemp, readFile, rm, writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join, resolve} from 'node:path';
import webpack from 'webpack';

const root=resolve(import.meta.dirname,'..');
const source=join(root,'games/php-poker/browser/mental-poker-source.mjs');
const target=join(root,'games/php-poker/browser/mental-poker.mjs');
const licenseTarget=target+'.LICENSE.txt';
const temporary=await mkdtemp(join(tmpdir(),'phonics-mental-poker-'));

try
{
	const compiler=webpack({
		mode:'production',entry:source,devtool:false,experiments:{outputModule:true},optimization:{minimize:true}
		,output:{path:temporary,filename:'mental-poker.mjs',library:{type:'module'},module:true,chunkFormat:'module'}
	});
	const stats=await new Promise((resolve,reject)=>compiler.run((error,result)=>compiler.close(closeError=>{
		if(error||closeError)reject(error??closeError);else resolve(result);
	})));
	if(stats.hasErrors())throw new Error(stats.toString({all:false,errors:true,errorDetails:true}));
	const banner='// Generated by scripts/build-mental-poker.mjs from mental-poker-source.mjs and @noble/curves 2.4.0.\n';
	const generated=banner+await readFile(join(temporary,'mental-poker.mjs'),'utf8');
	const generatedLicense=await readFile(join(temporary,'mental-poker.mjs.LICENSE.txt'),'utf8');
	if(process.argv.includes('--check'))
	{
		let existing='',existingLicense='';try{existing=await readFile(target,'utf8');}catch{}
		try{existingLicense=await readFile(licenseTarget,'utf8');}catch{}
		if(existing!==generated||existingLicense!==generatedLicense)throw new Error('PHP Poker mental-poker bundle is stale; run npm run generate');
	}
	else await Promise.all([writeFile(target,generated),writeFile(licenseTarget,generatedLicense)]);
}
finally{await rm(temporary,{recursive:true,force:true});}
